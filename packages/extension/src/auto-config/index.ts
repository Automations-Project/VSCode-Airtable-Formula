// Our local entry is MCP_SERVER_NAME ('airtable-user-mcp'); the official remote one:
const OFFICIAL_AIRTABLE_NAME = 'airtable';
const OFFICIAL_AIRTABLE_URL = 'https://mcp.airtable.com/mcp';

/** Stable directory for the launcher — never includes a version number. */
const LAUNCHER_DIR = path.join(os.homedir(), '.airtable-user-mcp');
const LAUNCHER_SCRIPT = path.join(LAUNCHER_DIR, 'start.mjs');
const LAUNCHER_CONFIG = path.join(LAUNCHER_DIR, 'bundled-path.json');

/** Launcher script content — a tiny resolver that reads the real path at startup. */
const LAUNCHER_SOURCE = `\
// Auto-generated by the Airtable Formula VS Code extension.
// This file provides a stable path for MCP configs so they survive extension updates.
// Do not edit — it is regenerated on every extension activation.
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dir = dirname(fileURLToPath(import.meta.url));
const config = JSON.parse(readFileSync(join(__dir, 'bundled-path.json'), 'utf8'));

// Ensure vendored dependencies (patchright, otpauth) are resolvable
if (config.nodePath) process.env.NODE_PATH = config.nodePath;

// Forward CLI args so subcommands (login, status, doctor) still work
const serverUrl = pathToFileURL(config.serverPath).href;
await import(serverUrl);
`;

/**
 * Write (or update) the stable launcher at ~/.airtable-user-mcp/.
 * Call this on every extension activation so bundled-path.json stays current.
 */
export async function ensureLauncher(serverPath: string): Promise<void> {
  const nodeModulesPath = path.resolve(path.dirname(serverPath), '..', 'node_modules');

  await fs.promises.mkdir(LAUNCHER_DIR, { recursive: true });

  // Always update bundled-path.json to point to the current extension version
  await fs.promises.writeFile(
    LAUNCHER_CONFIG,
    JSON.stringify({ serverPath, nodePath: nodeModulesPath }, null, 2) + '\n',
    'utf8',
  );

  // Write the launcher script (idempotent — content is static)
  await fs.promises.writeFile(LAUNCHER_SCRIPT, LAUNCHER_SOURCE, 'utf8');
}

export function buildServerEntry(_serverPath: string): Record<string, unknown> {
  const env: Record<string, string> = {
    AIRTABLE_HEADLESS_ONLY: '1',
    AIRTABLE_PROFILE_DIR: path.join(os.homedir(), '.airtable-user-mcp', '.chrome-profile'),
  };

  const settings = getSettings();
  const choice = settings.auth.browserChoice;
  if (choice?.channel) env.AIRTABLE_BROWSER_CHANNEL = choice.channel;
  if (choice?.executablePath) env.AIRTABLE_BROWSER_PATH = choice.executablePath;
  applyTransportEnv(env, settings);

  return {
    command: 'node',
    args: [LAUNCHER_SCRIPT],
    env,
  };
}

/**
 * Propagate the transport/auth-mode settings into an externally-written MCP config so a server
 * launched by another IDE (Claude Desktop, Cursor, …) starts in the SAME mode the user selected in
 * the extension — instead of silently defaulting to `browser`. Only non-defaults are injected (the
 * server's own defaults are `browser` + `fetch`). NOTE: byo/direct-login also need CREDENTIALS —
 * those reach a RUNNING daemon via its bearer-authed endpoint, and the launcher (`start.mjs`, no
 * args) attach-proxies external clients to that daemon; a standalone no-daemon server reads them from
 * `AIRTABLE_*` env or `~/.airtable-user-mcp/{credentials,login}.json`. The extension never writes
 * plaintext credentials into IDE configs.
 */
function applyTransportEnv(env: Record<string, string>, settings: ReturnType<typeof getSettings>): void {
  if (settings.mcp.authMode && settings.mcp.authMode !== 'browser') env.AIRTABLE_AUTH_MODE = settings.mcp.authMode;
  if (settings.mcp.httpClient === 'impit') env.AIRTABLE_HTTP_CLIENT = 'impit';
  env.AIRTABLE_BROWSER_IDLE_PARK_MS = String(minutesToIdleParkMs(settings.mcp.browserIdleParkMinutes));
}

export function buildNpxServerEntry(): Record<string, unknown> {
  const env: Record<string, string> = {
    AIRTABLE_HEADLESS_ONLY: '1',
    AIRTABLE_PROFILE_DIR: path.join(os.homedir(), '.airtable-user-mcp', '.chrome-profile'),
  };

  const settings = getSettings();
  const choice = settings.auth.browserChoice;
  if (choice?.channel) env.AIRTABLE_BROWSER_CHANNEL = choice.channel;
  if (choice?.executablePath) env.AIRTABLE_BROWSER_PATH = choice.executablePath;
  applyTransportEnv(env, settings);

  return {
    command: 'npx',
    args: ['-y', 'airtable-user-mcp'],
    env,
  };
}

/** This host's paths, file checks and launcher: what every function below uses unless a test passes its own. */
export function hostWriterDeps(): WriterDeps {
  return { ctx: hostPathContext(), exists: fs.existsSync, launcher: { script: LAUNCHER_SCRIPT, config: LAUNCHER_CONFIG } };
}

/**
 * Writes our entry in the client's current location, in the client's shape, and moves any copy
 * from an old location. An editor with no MCP row (Helix, Neovim) has nothing to write. Throws
 * when the client is not detected or a file does not parse; nothing is written then.
 */
export async function configureMcpForIde(
  ideId: IdeId,
  serverPath: string,
  serverEntry?: Record<string, unknown>,
  deps: WriterDeps = hostWriterDeps(),
): Promise<void> {
  const row = mcpRowFor(ideId);
  if (!row) return;
  const launch = readLaunch(serverEntry ?? buildServerEntry(serverPath));
  if (!launch) throw new Error('the MCP server entry has no command');
  await configureMcpClient(row, launch, deps);
}

/**
 * The activation auto-heal and the settings rewrite: re-writes the entry with the current settings
 * only when the client has one we wrote (isOurEntry). A hand-written entry, or none, is left
 * alone. Returns whether it re-wrote.
 */
export async function reapplyMcpForIde(
  ideId: IdeId,
  serverPath: string,
  serverEntry?: Record<string, unknown>,
  deps: WriterDeps = hostWriterDeps(),
): Promise<boolean> {
  const row = mcpRowFor(ideId);
  if (!row) return false;
  const found = await readServerEntry(row, MCP_SERVER_NAME, deps);
  if (!found || !isOurEntry(found.entry, deps)) return false;
  await configureMcpForIde(ideId, serverPath, serverEntry, deps);
  return true;
}

export async function unconfigureMcpForIde(ideId: IdeId, deps: WriterDeps = hostWriterDeps()): Promise<void> {
  const row = mcpRowFor(ideId);
  if (row) await unconfigureMcpClient(row, deps);
}

export async function getMcpHealth(ideId: IdeId, deps: WriterDeps = hostWriterDeps()): Promise<{ configured: boolean; healthy: boolean }> {
  const row = mcpRowFor(ideId);
  return row ? readMcpClientHealth(row, deps) : { configured: false, healthy: false };
}

export async function isMcpConfigured(ideId: IdeId, deps: WriterDeps = hostWriterDeps()): Promise<boolean> {
  return (await getMcpHealth(ideId, deps)).configured;
}

function missingAiSkill(): AiSkill {
  return { status: 'missing' };
}

export async function getIdeStatus(ideId: IdeId, deps: WriterDeps = hostWriterDeps()): Promise<IdeStatus> {
  const cfg = IDE_CONFIGS[ideId];
  const detected = await isIdeInstalled(ideId, deps.ctx, deps.exists);
  const hasMcp = cfg.capabilities.includes('mcp');
  const hasLsp = cfg.capabilities.includes('lsp');
  const health = (detected && hasMcp)
    ? await getMcpHealth(ideId, deps)
    : { configured: false, healthy: false };
  const lspConfigured = (detected && hasLsp)
    ? await isLspConfigured(ideId)
    : undefined;
  return {
    ideId,
    label: cfg.label,
    detected,
    mcpConfigured: health.configured,
    mcpServerHealthy: health.configured ? health.healthy : undefined,
    lspConfigured:   hasLsp ? lspConfigured : undefined,
    lspManualStep:   cfg.lspManualStep,
    aiSkill: missingAiSkill(),
  };
}

/** One status per IdeId, in IDE_IDS order. Every id has MCP or LSP, so every one gets a card. */
export async function getAllIdeStatuses(deps: WriterDeps = hostWriterDeps()): Promise<IdeStatus[]> {
  return Promise.all(IDE_IDS.map(id => getIdeStatus(id, deps)));
}

// ── Official Airtable MCP (https://mcp.airtable.com/mcp) ───────────────────

/**
 * The official entry in the row's shape. `loc.native` is OpenCode's V2 key (`mcp.servers`), where
 * `enabled` is omitted, as for our local entry.
 */
export function buildOfficialAirtableEntry(row: McpClientRow, pat: string, loc: { native: boolean } = { native: false }): Record<string, unknown> {
  const headers = { Authorization: `Bearer ${pat}` };
  // OpenCode knows `local` and `remote` servers only: add-mcp's transformOpenCodeConfig remote branch.
  if (row.layout === 'opencode') {
    return loc.native
      ? { type: 'remote', url: OFFICIAL_AIRTABLE_URL, headers }
      : { type: 'remote', url: OFFICIAL_AIRTABLE_URL, headers, enabled: true };
  }
  // Windsurf uses 'serverUrl'; all other MCP clients use 'url'.
  // Claude Code (and most MCP clients) also require "type": "http" to recognise
  // remote HTTP servers — without it the entry is silently ignored.
  return row.official === 'serverUrl'
    ? { serverUrl: OFFICIAL_AIRTABLE_URL, headers }
    : { type: 'http', url: OFFICIAL_AIRTABLE_URL, headers };
}

/**
 * The row whose 'airtable' entry can be ours: only the eight rows with `official` set. Anywhere
 * else an 'airtable' server is the user's own, so it is never read, written or removed as ours.
 */
function officialRowFor(ideId: IdeId): McpClientRow | null {
  const row = mcpRowFor(ideId);
  return row?.official ? row : null;
}

/** On those rows, an 'airtable' entry is ours only while it points at the official server. */
const isOfficialEntry = (entry: Record<string, unknown>): boolean =>
  entry.url === OFFICIAL_AIRTABLE_URL || entry.serverUrl === OFFICIAL_AIRTABLE_URL;

/**
 * Configured: ours, where the client reads it, and in the shape we write now (so OpenCode's old
 * `type: 'http'` copy is not). Anything less is cleaned up by the next Configure.
 */
function isOfficialEntryCurrent(row: McpClientRow, found: FoundEntry): boolean {
  if (found.legacy) return false;
  const expected = buildOfficialAirtableEntry(row, '', { native: found.native });
  return Object.keys(expected).every(k => Object.prototype.hasOwnProperty.call(found.entry, k))
    && (expected.type === undefined || found.entry.type === expected.type);
}

export async function configureOfficialAirtableMcp(ideId: IdeId, pat: string, deps: WriterDeps = hostWriterDeps()): Promise<void> {
  const row = officialRowFor(ideId);
  if (!row) throw new Error(`${IDE_CONFIGS[ideId].label} does not support the official Airtable server here.`);
  await setServerEntry(row, OFFICIAL_AIRTABLE_NAME, ({ native, existing }) => {
    // The write would replace whatever holds the name there; a server of the user's own is not
    // ours to replace. Checked inside the writer's file lock, so nothing can slip in between.
    if (existing !== undefined && !(isRecord(existing) && isOfficialEntry(existing))) {
      throw new Error(`${row.label} already has an "airtable" MCP server that is not Airtable's official one; rename it first`);
    }
    return buildOfficialAirtableEntry(row, pat, { native });
  }, deps, isOfficialEntry);
}

const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

export async function unconfigureOfficialAirtableMcp(ideId: IdeId, deps: WriterDeps = hostWriterDeps()): Promise<void> {
  const row = officialRowFor(ideId);
  if (row) await setServerEntry(row, OFFICIAL_AIRTABLE_NAME, null, deps, isOfficialEntry);
}

export async function isOfficialAirtableConfigured(ideId: IdeId, deps: WriterDeps = hostWriterDeps()): Promise<boolean> {
  const row = officialRowFor(ideId);
  if (!row) return false;
  try {
    const found = await readServerEntry(row, OFFICIAL_AIRTABLE_NAME, deps, isOfficialEntry);
    return found !== null && isOfficialEntryCurrent(row, found);
  } catch { return false; }
}

