// node --test scripts/vendor-language-services.test.mjs
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { vendorLanguageServices, VENDOR_PATH, SOURCE_PATH } from './vendor-language-services.mjs';

const FAKE_DIST = 'export function formulaDiagnostics(){return[]}\nexport function scriptDiagnostics(){return[]}\nexport function automationDiagnostics(){return[]}\nexport var LsSeverity={};\n';

function fakeRoot(dist = FAKE_DIST) {
  const root = mkdtempSync(join(tmpdir(), 'vendor-ls-'));
  mkdirSync(join(root, 'packages/language-services/dist'), { recursive: true });
  mkdirSync(join(root, 'packages/mcp-server/src'), { recursive: true });
  writeFileSync(join(root, SOURCE_PATH), dist);
  return root;
}

test('generates the vendored file with a generated-file header', () => {
  const root = fakeRoot();
  const r = vendorLanguageServices({ root, check: false });
  assert.equal(r.ok, true);
  const out = readFileSync(join(root, VENDOR_PATH), 'utf8');
  assert.match(out, /^\/\/ GENERATED by scripts\/vendor-language-services\.mjs/);
  assert.ok(out.includes('export function automationDiagnostics'));
});

test('check passes when the vendored file matches, ignoring CRLF', () => {
  const root = fakeRoot();
  vendorLanguageServices({ root, check: false });
  const p = join(root, VENDOR_PATH);
  writeFileSync(p, readFileSync(p, 'utf8').replace(/\n/g, '\r\n'));
  assert.equal(vendorLanguageServices({ root, check: true }).ok, true);
});

test('check fails when the engine source changed', () => {
  const root = fakeRoot();
  vendorLanguageServices({ root, check: false });
  writeFileSync(join(root, SOURCE_PATH), FAKE_DIST + '// changed\n');
  const r = vendorLanguageServices({ root, check: true });
  assert.equal(r.ok, false);
  assert.match(r.message, /pnpm vendor:language-services/);
});

test('check fails when the vendored file is missing', () => {
  const root = fakeRoot();
  assert.equal(vendorLanguageServices({ root, check: true }).ok, false);
});

test('refuses a dist that lacks one of the three engines', () => {
  const root = fakeRoot(FAKE_DIST.replace('automationDiagnostics', 'somethingElse'));
  assert.throws(() => vendorLanguageServices({ root, check: false }), /automationDiagnostics/);
});

test('refuses a missing dist with a build hint', () => {
  const root = mkdtempSync(join(tmpdir(), 'vendor-ls-'));
  assert.throws(() => vendorLanguageServices({ root, check: false }), /pnpm -F language-services build/);
  assert.equal(existsSync(join(root, VENDOR_PATH)), false);
});
