#!/usr/bin/env node
/**
 * Vendor the language-services ESM build into the MCP server.
 *
 * `airtable-user-mcp` is published to npm straight from `src/` with no build
 * step, so it cannot import the private `language-services` workspace package.
 * This copies `packages/language-services/dist/index.js` (plus a header) to
 * `packages/mcp-server/src/vendor/language-services.mjs`, committed so the
 * published package carries it.
 *
 *   node scripts/vendor-language-services.mjs           # (re)write the vendored file
 *   node scripts/vendor-language-services.mjs --check   # fail if it is stale or missing
 *
 * Both modes need `pnpm -F language-services build` to have run first.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SOURCE_PATH = 'packages/language-services/dist/index.js';
export const VENDOR_PATH = 'packages/mcp-server/src/vendor/language-services.mjs';
const REQUIRED_EXPORTS = ['formulaDiagnostics', 'scriptDiagnostics', 'automationDiagnostics'];

const HEADER = [
  '// GENERATED by scripts/vendor-language-services.mjs from packages/language-services/dist/index.js',
  '// Do not edit. Regenerate with: pnpm vendor:language-services',
  '// Checked by: pnpm check:vendor (runs in pnpm build)',
  '',
].join('\n');

const lf = text => text.replace(/\r\n/g, '\n');

export function vendorLanguageServices({ root = process.cwd(), check = false } = {}) {
  const src = join(root, SOURCE_PATH);
  if (!existsSync(src)) {
    throw new Error(`${SOURCE_PATH} not found; run \`pnpm -F language-services build\` first`);
  }
  const source = lf(readFileSync(src, 'utf8'));
  for (const name of REQUIRED_EXPORTS) {
    if (!source.includes(name)) throw new Error(`${SOURCE_PATH} does not contain ${name}; refusing to vendor it`);
  }
  const expected = HEADER + source;
  const out = join(root, VENDOR_PATH);

  if (check) {
    // Tolerate CRLF checkouts (autocrlf) when comparing against the LF output.
    const committed = existsSync(out) ? lf(readFileSync(out, 'utf8')) : null;
    if (committed === expected) return { ok: true, message: `${VENDOR_PATH} is up to date` };
    return {
      ok: false,
      message: `${VENDOR_PATH} is ${committed === null ? 'missing' : 'stale'}; run \`pnpm vendor:language-services\``,
    };
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, expected);
  return { ok: true, message: `wrote ${VENDOR_PATH} (${expected.length} bytes)` };
}

export function main(argv = process.argv.slice(2)) {
  try {
    const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
    const r = vendorLanguageServices({ root, check: argv.includes('--check') });
    if (!r.ok) {
      console.error(`\x1b[31m✗ vendor-language-services: ${r.message}\x1b[0m`);
      process.exit(1);
    }
    console.log(r.ok && argv.includes('--check') ? `\x1b[32m✓ vendor-language-services: ${r.message}\x1b[0m` : `vendor-language-services: ${r.message}`);
  } catch (err) {
    console.error(`\x1b[31m✗ vendor-language-services: ${err.message}\x1b[0m`);
    process.exit(1);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
